const { app } = require('electron')
const Database = require('better-sqlite3')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const vm = require('node:vm')
const root = path.join(__dirname, '..')

app.whenReady().then(async () => {
    const db = new Database(':memory:')
    const schema = fs.readFileSync(path.join(root, 'src/main/DB/tableInfo.js'), 'utf8').replace(/export[\s\S]*$/, '')
    for (const sql of vm.runInNewContext(schema + '\ninit_table')) db.exec(sql)
    const queryAll = (sql, params) => db.prepare(sql).all(params).map(row => Object.fromEntries(
        Object.entries(row).map(([key, value]) => [key.replace(/_([a-z])/g, (_, letter) => letter.toUpperCase()), value])))
    const source = fs.readFileSync(path.join(root, 'src/main/DB/select.js'), 'utf8')
        .replace(/^import .*\r?\n/gm, '').replace(/export[\s\S]*$/, '')
    const selectors = vm.runInNewContext(source + '\n({ searchLocal, loadMessage })', { queryAll, computedOffset: total => ({ pageTotal: Math.ceil(total / 30), pageSize: 30, offset: 0 }), console: { log() {} } })
    const search = selectors.searchLocal
    const friend = db.prepare('insert into friend_relation (user_id, friend_id, username, account, avatar, gender, phone, remark, relation_status) values (?, ?, ?, ?, ?, ?, ?, ?, ?)')
    friend.run(101, 1, 'Alice 项目设计', 'alice_01', '', 0, '13800000001', '设计伙伴', 1)
    friend.run(202, 2, '另一个账号的项目联系人', 'other', '', 0, '13800000002', '', 1)
    friend.run(101, 3, '尚未通过的联系人', 'pending', '', 0, '13800000003', '', 0)
    const conversation = db.prepare('insert into conversation (id, user_id, target_id, name, type, status) values (?, ?, ?, ?, ?, ?)')
    conversation.run('dm-101', 101, '1', '项目讨论', 0, 1)
    conversation.run('group-101', 101, 'group', '项目群', 1, 1)
    conversation.run('hidden-101', 101, 'hidden', '归档项目', 0, 0)
    conversation.run('dm-202', 202, '2', '其他账号项目', 0, 1)
    conversation.run('ai-101', 101, 'ai', '项目 Agent', 2, 1)
    const message = db.prepare('insert into message (id, sender_id, receiver_id, conversation_id, msg_type, content, file_name, is_deleted, is_revoked) values (?, 101, ?, ?, ?, ?, ?, ?, ?)')
    message.run('message-ok', '1', 'dm-101', 1, '今天讨论项目设计', null, 0, 0)
    message.run('message-file', 'group', 'group-101', 5, '[文件]', '项目说明.pdf', 0, 0)
    message.run('message-hidden', 'hidden', 'hidden-101', 1, '归档项目内容', null, 0, 0)
    message.run('message-deleted', '1', 'dm-101', 1, '项目已删除', null, 1, 0)
    message.run('message-revoked', '1', 'dm-101', 1, '项目已撤回', null, 0, 1)
    message.run('message-other', '2', 'dm-202', 1, '其他账号项目消息', null, 0, 0)
    message.run('message-ai', 'ai', 'ai-101', 1, '项目 AI 消息', null, 0, 0)
    message.run('message-literal', '1', 'dm-101', 1, '完成 100% 的 a_b! 文档', null, 0, 0)
    const all = search(101, '项目')
    assert.equal(all.contacts.length, 1)
    assert.equal(all.conversations.length, 3)
    assert.equal(all.messages.length, 3)
    assert.ok(all.messages.every(item => !['message-deleted', 'message-revoked', 'message-other', 'message-ai'].includes(item.id)))
    assert.equal(search(101, 'ALICE').contacts[0].friendId, 1)
    assert.equal(search(101, '伙伴').contacts.length, 1)
    assert.equal(search(101, 'alice_01').contacts.length, 1)
    const contacts = search(101, '项目', 'contacts')
    assert.equal(contacts.contacts.length, 1)
    assert.equal(contacts.messages.length, 0)
    assert.equal(contacts.conversations.length, 0)
    for (const query of ['%', '_', '!']) assert.equal(search(101, query).messages[0].id, 'message-literal')
    assert.equal(search(101, "%' OR 1=1 --").messages.length, 0)
    assert.equal(search(101, '').messages.length, 0)
    assert.equal(search(null, '项目').contacts.length, 0)
    for (let index = 10; index < 50; index++) friend.run(101, index, '匹配联系人' + index, 'test' + index, '', 0, '13800000000', '', 1)
    assert.equal(search(101, '匹配').contacts.length, 30)
    for (let index = 0; index < 100; index++) message.run('seq-' + String(index).padStart(4, '0'), '1', 'dm-101', 1, '历史消息 ' + index, null, 0, 0)
    const latest = selectors.loadMessage('dm-101', { pageNO: 0 }, 101)
    assert.equal(latest.dataList.some(item => item.id === 'seq-0050'), false)
    const around = selectors.loadMessage('dm-101', { pageNO: 0, anchorMessageId: 'seq-0050' }, 101)
    assert.equal(around.anchorFound, true)
    assert.equal(around.dataList.length, 41)
    assert.equal(around.dataList[0].id, 'seq-0070')
    assert.equal(around.dataList.at(-1).id, 'seq-0030')
    assert.equal(selectors.loadMessage('dm-101', { pageNO: 0, anchorMessageId: 'seq-0050' }, 202).anchorFound, false)
    assert.equal(selectors.loadMessage('dm-101', { pageNO: 0, anchorMessageId: 'missing' }, 101).anchorFound, false)
    const handlers = new Map()
    const ipcSource = fs.readFileSync(path.join(root, 'src/main/IPC/DBIPC.js'), 'utf8').replace(/^import .*\r?\n/gm, '')
    vm.runInNewContext(ipcSource, { ipcMain: { on() {}, handle: (name, callback) => handlers.set(name, callback) },
        store: { get: () => 101 }, searchLocal: search, console })
    const scoped = await handlers.get('search:local')({}, { query: '项目', userId: 202 })
    assert.equal(scoped.contacts[0].friendId, 1)
    db.close()
    console.log('本地搜索：真实 SQLite 模糊查询、账号隔离、分类、文件名、删除撤回过滤、通配符、结果上限与 IPC 账号绑定通过')
    app.exit(0)
}).catch(error => { console.error(error); app.exit(1) })
